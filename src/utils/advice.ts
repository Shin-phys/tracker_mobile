// src/utils/advice.ts
// ============================================================
// 追跡が飛んだ・見失ったときに「次に試すこと」を数値で出す。
//
// 文章で「探索範囲を狭めてください」と言うだけでは、いくつにすれば
// よいのかが分からない。現在の値から次の候補を計算して、そのまま
// 適用できる形で渡す。すでに下限なら何も出さない（できないことを
// 勧めない）。
// ============================================================

/** 探索範囲（枠に対する倍率）の下限。これ以下にすると急な変化を拾えない */
export const MIN_SEARCH_SCALE = 0.4;

/**
 * 次に試す探索範囲。下げる余地がなければ null。
 *
 * なぜ下げるのが効くのか
 *   等速度予測が当たっている限り、窓が吸収すべきなのは移動量ではなく
 *   移動量の変化。広い窓は「似た模様」に乗り移る機会を増やすだけで、
 *   追跡の役には立たない。丸シールのような目印を使っているなら、
 *   目印そのものは見分けがつくので、窓は狭いほど有利になる。
 *
 *   合成データでの実測（直径 18px の白シール、経路の外に同じ印が並ぶ）
 *     半径 48px（枠 x1.2）… 別の印に乗り移り（誤差 680px）
 *     半径 24px 以下      … 誤差 0.0px
 */
export function narrowerSearchScale(cur: number): number | null {
  const next = Math.round((cur - 0.2) * 10) / 10;
  if (next < MIN_SEARCH_SCALE - 1e-9) return null;
  return next;
}

/**
 * 次に試す再生速度。落とす余地がなければ null。
 *
 * なぜ落とすのが効くのか
 *   再生しながらの処理は requestVideoFrameCallback に乗っているので、
 *   1 コマ分の処理が実時間のフレーム間隔に間に合わないと、その間に
 *   提示されたコマは呼ばれないまま通り過ぎる。取りこぼすと、記録の上では
 *   1 コマの移動量が倍（2 コマ落とせば 3 倍）になり、探索窓を超える。
 *   つまり「速度を落とすと追尾がうまくいく」のは、取りこぼす確率を
 *   下げているだけ。ゼロにはならないが、効果は確かにある。
 *
 * @param rates 選べる速度の一覧（昇順でなくてよい）
 */
export function slowerRate(cur: number, rates: number[]): number | null {
  const below = rates.filter(r => r < cur - 1e-9).sort((a, b) => b - a);
  return below.length > 0 ? below[0] : null;
}

/** 再生速度の表示（1/4 など） */
export function rateLabel(v: number): string {
  if (v >= 1) return `${v}×`;
  const d = Math.round(1 / v);
  return `1/${d}`;
}
